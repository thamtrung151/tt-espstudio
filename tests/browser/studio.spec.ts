test('local API rejects unauthenticated builds and foreign origins', async ({ request }) => {
  expect((await request.post('/api/build', { data: { code: 'x' } })).status()).toBe(403);
  expect((await request.get('/api/session', { headers: { Origin: 'https://example.com' } })).status()).toBe(403);
  const session = await (await request.get('/api/session')).json();
  expect((await request.post('/api/build', { headers: { 'X-Studio-Token': session.token }, data: { config: {}, code: 'x' } })).status()).toBe(400);
});
