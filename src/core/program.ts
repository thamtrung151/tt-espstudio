import { z } from 'zod';
import { configSchema, type Config, type Device, type Driver, parseConfig, allocatePwm, devicePins } from './config';
import { driverRegistry, digitalWriteCode, readCode, motorHelpers } from './drivers';

export type Statement =
  | { kind: 'write'; id: string; device: string; on: boolean }
  | { kind: 'wait'; id: string; ms: number }
  | { kind: 'print'; id: string; text: string }
  | { kind: 'read'; id: string; device: string }
  | { kind: 'pwm'; id: string; device: string; percent: number }
  | { kind: 'servo'; id: string; device: string; angle: number }
  | { kind: 'servo_release'; id: string; device: string }
  | { kind: 'motor'; id: string; device: string; power: number; ms: number }
  | { kind: 'motor_stop'; id: string; device: string }
  | { kind: 'if'; id: string; device: string; operator: string; value: number; then: Statement[]; otherwise: Statement[] }
  | { kind: 'repeat'; id: string; count: number; body: Statement[] };
export type Program = { setup: Statement[]; loop: Statement[] };
export type Generated = { code: string; ranges: Record<string, { start: number; end: number }> };

export function generate(config: Config, program: Program): Generated {
  parseConfig(config);
  const channels = allocatePwm(config);
  const declarations = config.devices.flatMap(d => devicePins(d).map(p => `constexpr uint8_t ${d.driver === 'motor.hbridge2' ? 'motor_' + d.id + '_' + p.field : 'pin_' + d.id} = ${p.pin};`));
  const lines = ['// Generated by TT ESPStudio. Arduino C++.', '#include <Arduino.h>', '', ...declarations, ...Object.entries(channels).map(([id, channel]) => `constexpr uint8_t ${id.includes(':') ? 'motor_channel_' + id.replace(':', '_') : 'channel_' + id} = ${channel};`), ''];
  for (const d of config.devices) if (d.driver === 'motor.hbridge2') lines.push(...motorHelpers(d));
  lines.push('void setup() {', '  Serial.begin(115200);');
  const ranges: Generated['ranges'] = {};
  for (const d of config.devices) for (const line of driverRegistry[d.driver].initialize(d)) lines.push(`  ${line}`);
  function device(id: string, allowed: Driver[]): Device {
    if (id === '__missing__') throw new Error('Block chưa chọn thiết bị. Chọn thiết bị đúng loại trong danh sách của block; PWM output dùng block PWM, motor IN1/IN2 dùng block Motor.');
    const d = config.devices.find(d => d.id === id);
    if (!d) throw new Error(`Thiết bị “${id}” không còn trong Configuration.`);
    if (!allowed.includes(d.driver)) throw new Error(`${id}: block không phù hợp loại thiết bị ${d.driver}.`);
    return d;
  }
  function integer(value: number, min: number, max: number, name: string) {
    if (!Number.isInteger(value) || value < min || value > max) throw new Error(`${name}: phải từ ${min} đến ${max}.`);
    return value;
  }
  let sequence = 0;
  function emit(statements: Statement[], depth: number) {
    if (depth > 12) throw new Error('Vòng lặp lồng nhau quá sâu (tối đa 12).');
    for (const s of statements) {
      const start = lines.length + 1; const pad = '  '.repeat(depth);
      switch (s.kind) {
        case 'write': {
          lines.push(pad + digitalWriteCode(device(s.device, ['gpio.output']), s.on)); break;
        }
        case 'read': {
          const d = device(s.device, ['gpio.input','adc.input']);
          lines.push(`${pad}Serial.print("${d.id}=");`, `${pad}Serial.println(${readCode(d)});`); break;
        }
        case 'pwm': {
          device(s.device, ['pwm.output']); integer(s.percent, 0, 100, 'PWM (%)');
          lines.push(`${pad}ledcWrite(channel_${s.device}, ${Math.round(s.percent * 255 / 100)});`); break;
        }
        case 'servo': {
          const d = device(s.device, ['servo.pwm']); if (d.driver !== 'servo.pwm') throw new Error('Driver mismatch');
          integer(s.angle, 0, 180, 'Góc servo');
          const pulse = d.minUs + (d.maxUs - d.minUs) * s.angle / 180;
          lines.push(`${pad}ledcWrite(channel_${d.id}, ${Math.round(pulse * 16384 / 20000)}); // ${s.angle} deg, ${Math.round(pulse)} us`); break;
        }
        case 'servo_release': device(s.device, ['servo.pwm']); lines.push(`${pad}ledcWrite(channel_${s.device}, 0); // Stop servo pulses`); break;
        case 'motor': device(s.device, ['motor.hbridge2']); integer(s.power, -100, 100, 'Motor (%)'); integer(s.ms, 1, 10000, 'Thời gian motor (ms)'); lines.push(`${pad}run_${s.device}(${s.power}, ${s.ms});`); break;
        case 'motor_stop': device(s.device, ['motor.hbridge2']); lines.push(`${pad}stop_${s.device}();`); break;
        case 'if': {
          const d = device(s.device, ['gpio.input','adc.input']); integer(s.value, 0, d.driver === 'gpio.input' ? 1 : 4095, 'Giá trị so sánh');
          if (!['==','!=','<','>','<=','>='].includes(s.operator)) throw new Error('Phép so sánh không hợp lệ.');
          lines.push(`${pad}if (${readCode(d)} ${s.operator} ${s.value}) {`); emit(s.then, depth + 1);
          lines.push(`${pad}} else {`); emit(s.otherwise, depth + 1); lines.push(`${pad}}`); break;
        }
        case 'wait':
          if (!Number.isInteger(s.ms) || s.ms < 0 || s.ms > 60000) throw new Error('Thời gian chờ phải từ 0 đến 60000 ms.');
          lines.push(`${pad}delay(${s.ms});`); break;
        case 'print': {
          if (s.text.length > 200) throw new Error('Nội dung serial tối đa 200 ký tự.');
          // Keep ordinary ASCII readable; quotes, backslashes and UTF-8 use
          // fixed-width octal escapes so no input can terminate the C++ literal.
          const literal = [...new TextEncoder().encode(s.text)].map(b => b >= 32 && b <= 126 && b !== 34 && b !== 92 ? String.fromCharCode(b) : `\\${b.toString(8).padStart(3, '0')}`).join('');
          lines.push(`${pad}Serial.println("${literal}");`); break;
        }
        case 'repeat': {
          if (!Number.isInteger(s.count) || s.count < 1 || s.count > 1000) throw new Error('Số lần lặp phải từ 1 đến 1000.');
          const index = `repeat_${sequence++}`;
          lines.push(`${pad}for (int ${index} = 0; ${index} < ${s.count}; ++${index}) {`);
          emit(s.body, depth + 1); lines.push(`${pad}}`); break;
        }
        default: throw new Error('Loại lệnh không được hỗ trợ.');
      }
      ranges[s.id] = { start, end: lines.length };
    }
  }
  emit(program.setup, 1); lines.push('}', '', 'void loop() {'); emit(program.loop, 1);
  lines.push('  delay(1); // Yield to the ESP32 scheduler.', '}', '');
  return { code: lines.join('\n'), ranges };
}
export const projectSchema = z.object({
  schemaVersion: z.literal(1), name: z.string().min(1).max(80), config: configSchema,
  mode: z.enum(['blocks', 'code']), workspace: z.record(z.string(), z.unknown()),
  code: z.string().max(200000),
  codeHistory: z.array(z.object({ savedAt: z.string(), code: z.string().max(200000), config: configSchema }).strict()).max(50),
}).strict();
export type Project = z.infer<typeof projectSchema>;
export function returnToBlocks(project: Project): Project {
  if (project.mode === 'blocks') return project;
  if (project.codeHistory.length >= 50) throw new Error('Đã có 50 bản C++ lưu lại. Xuất project và dọn lịch sử trước khi chuyển tiếp.');
  return { ...project, mode: 'blocks', codeHistory: [...project.codeHistory, { savedAt: new Date().toISOString(), code: project.code, config: structuredClone(project.config) }] };
}
